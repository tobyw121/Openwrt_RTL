        {
            hal_miim_pollingEnable_get(unit, i, &restore_flag[(i - rtl8214_phy0_macid)]);
            hal_miim_pollingEnable_set(unit, i, enable_flag);
        }

        /*Reset PHY again*/
        hal_miim_write(unit,  rtl8214_phy0_macid,  0x0,  30, 0x8);
        hal_miim_write(unit,  rtl8214_phy0_macid,  0x262,  16, 0x1);

