            ret = hal_miim_write(unit,  port,  0x424,  0x10, phy_data);
            if(ret != RT_ERR_OK)
                return ret;

            phy_data = 0;
            ret = hal_miim_write(unit,  port,  0,  30, phy_data);
            if(ret != RT_ERR_OK)
                return ret;


            /* Set PKTGEN RXPATH is from MAC TX & Enable PKTGEN RX for Phy error counter */
            for(port_id = 0; port_id < 8; port_id++)
            {
                ret = hal_miim_read(unit,  port+port_id,  0xc80,  16, &phy_data);
                if(ret != RT_ERR_OK)
                    return ret;

                phy_data &= ~0xF;
                phy_data |= 0x1<<2;
                phy_data |= 0x2<<0;
                ret = hal_miim_write(unit,  port+port_id,  0xc80,  16, phy_data);
                if(ret != RT_ERR_OK)
                    return ret;
            }

