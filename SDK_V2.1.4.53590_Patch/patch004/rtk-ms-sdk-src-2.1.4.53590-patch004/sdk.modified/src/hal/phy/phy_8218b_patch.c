             if ((ret = hal_miim_write(unit, port, 0, 27, 0x801e)) != RT_ERR_OK)
                 return ret;
             if ((ret = hal_miim_write(unit, port, 0, 28, 0x1)) != RT_ERR_OK)
                 return ret;

