/* Function Name:
 *      rtl8390_rtl8218b_config
 * Description:
 *      Configuration code for RTL8218b.
 * Input:
 *      macId - the macId of PHY0 of the RTL8218b
 * Output:
 *      None
 * Return:
 *      None
 * Note:
 *      None
 */
int32 rtl8390_rtl8218b_config(uint32 unit, rtk_port_t macId)
{
    int base_id = macId - (macId % 8);
    int portId;
    uint32 val;
    int i;
    uint32 rl_no = 0, ver_no = 0, romId;
    int32  ret = RT_ERR_FAILED;
    rtk_enable_t enable_flag, restore_flag[8];

    hal_miim_read(unit, base_id, 0, 3, &val);

    if ((val & 0x3FF) == 0x180)
    {
        RT_DBG(LOG_DEBUG, (MOD_HAL|MOD_SWITCH), "### %d invalid RTL8218B ###\n", macId);
        return ret;
    }

    /*Re-Patch PHYs which have been reseted*/
    /*Save polling mask*/
    enable_flag = DISABLED;
    for (i = base_id; i < (base_id + 8); ++i)
    {
        hal_miim_pollingEnable_get(unit, i, &restore_flag[(i - base_id)]);
        hal_miim_pollingEnable_set(unit, i, enable_flag);
    }

    /*Reset PHY again*/
    hal_miim_write(unit, base_id, 0x0, 29, 0x8);
    hal_miim_write(unit, base_id, 0x262, 16, 0x1);

     /*Delay until PHY reset done*/
    osal_time_usleep(100 * 1000); /* delay 100mS */

    hal_miim_write(unit, base_id, RTL8390_MAX_PAGE, 29, 0x0001);
    hal_miim_write(unit, base_id, 0xa43, 19, 0x0002);
    hal_miim_read(unit, base_id, 0xa43, 20, &rl_no);
    hal_miim_write(unit, base_id, RTL8390_MAX_PAGE, 29, 0x0000);

    /* MP */
    if (RTL8218B_CHIP_ID == rl_no)
    {
        /* Version */
        hal_miim_write(unit, base_id, RTL8390_MAX_PAGE, 19, 0x0004);
        hal_miim_read(unit, base_id, RTL8390_MAX_PAGE, 20, &ver_no);

        hal_miim_write(unit, base_id, RTL8390_MAX_PAGE, 27, 0x0004);
        hal_miim_read(unit, base_id, RTL8390_MAX_PAGE, 28, &romId);

        RT_DBG(LOG_DEBUG, (MOD_HAL|MOD_SWITCH), "### RTL8218B config - MAC ID = %d ###\n", base_id);

        /* Per-Chip */
         for (i = 0; i < (sizeof(rtl8218b_6276A_rtl8390_perchip)/sizeof(phy_patch_array_type0_t)); ++i)
        {
            hal_miim_park_write(unit, base_id + rtl8218b_6276A_rtl8390_perchip[i].phy, \
                    RTL8390_MAX_PAGE, 0x1f, \
                    (int)rtl8218b_6276A_rtl8390_perchip[i].reg,  \
                    rtl8218b_6276A_rtl8390_perchip[i].val);
        }

        for (i = 0; i < (sizeof(rtl8218b_6276A_rtl8390_perchip2)/sizeof(phy_patch_array_type2_t)); ++i)
        {
            PHY_PATCH_SET(base_id, RTL8390_MAX_PAGE, rtl8218b_6276A_rtl8390_perchip2[i]);
        }

        for (i = 0; i < (sizeof(rtl8218b_6276A_rtl8390_perchip3)/sizeof(phy_patch_array_type0_t)); ++i)
        {
            hal_miim_park_write(unit, base_id + rtl8218b_6276A_rtl8390_perchip3[i].phy, \
                    RTL8390_MAX_PAGE, 0x1f, \
                    (int)rtl8218b_6276A_rtl8390_perchip3[i].reg,  \
                    rtl8218b_6276A_rtl8390_perchip3[i].val);
        }

        for (portId = 0; portId < 8; ++portId)
        {
            int pid = base_id + portId;

            for (i = 0; i < (sizeof(rtl8218b_6276A_rtl8390_perport)/sizeof(phy_patch_array_type1_t)); ++i)
                hal_miim_park_write(unit, pid, RTL8390_MAX_PAGE, 0x1f, \
                        (int)rtl8218b_6276A_rtl8390_perport[i].reg, \
                        rtl8218b_6276A_rtl8390_perport[i].val);
        }

        hal_miim_write(unit, base_id, RTL8390_MAX_PAGE, 30, 8);
        hal_miim_write(unit, base_id, 0x26e, 17, 0xb);
        hal_miim_write(unit, base_id, 0x26e, 16, 0x2);
        osal_time_usleep(1000);
        hal_miim_read(unit, base_id, 0x26e, 19, &val);
        hal_miim_write(unit, base_id, RTL8390_MAX_PAGE, 30, 0);

        val = (val >> 4) & 0xf;
        if (1 == val)
        {
            for (portId = 0; portId < 8; ++portId)
            {
                int pid = base_id + portId;

                for (i = 0; i < (sizeof(rtl8218b_6276C_rtl8390_IPD_perport)/sizeof(phy_patch_array_type1_t)); ++i)
                    hal_miim_park_write(unit, pid, RTL8390_MAX_PAGE, 0x1f, \
                            (int)rtl8218b_6276C_rtl8390_IPD_perport[i].reg, \
                            rtl8218b_6276C_rtl8390_IPD_perport[i].val);
            }

            for (i = 0; i < (sizeof(rtl8218b_6276C_rtl8390_IPD_perchip)/sizeof(phy_patch_array_type0_t)); ++i)
            {
                hal_miim_park_write(unit, base_id + rtl8218b_6276C_rtl8390_IPD_perchip[i].phy, \
                        RTL8390_MAX_PAGE, 0x1f, \
                        (int)rtl8218b_6276C_rtl8390_IPD_perchip[i].reg,  \
                        rtl8218b_6276C_rtl8390_IPD_perchip[i].val);
            }
        }
    }
    /* ES */
    else
    {
        int port_id;
        uint32 cut_id;

        /*Switch to right TOP address*/
        hal_miim_write(unit, base_id, 0, 29, 0x0000);

        /*Check the 8218B internal chip ID*/
        hal_miim_write(unit, base_id, 0x0a42, 27, 0x0002);
        hal_miim_read(unit, base_id, 0x0a42, 28, &val);

        /*Check the 8218B internal cut ID*/
        hal_miim_write(unit, base_id, 0x0a42, 27, 0x0004);
        hal_miim_read(unit, base_id, 0x0a42, 28, &cut_id);

        /*Check the 8218B status*/
        hal_miim_write(unit, base_id, 0x0a42, 31, 0xa42);
        hal_miim_read(unit, base_id, 0x0a42, 16, &val);

        //RT_DBG(LOG_DEBUG, (MOD_HAL|MOD_SWITCH), "### RTL8218B config - MAC ID = %d, Mode = 0x%08x ###\n", base_id, val);
        RT_DBG(LOG_DEBUG, (MOD_HAL|MOD_SWITCH), "### RTL8218B config - MAC ID = %d cut_id %d###\n", base_id, cut_id);

        if(cut_id == RTL8218B_TCA_CUT_A)
        {
            if(val == 2) /* ext init mode*/
            {
                for (i=0; i<(sizeof(rtl8218b_0455A_mode2_perchip)/sizeof(phy_patch_array_type0_t)); i++)
                {
                    hal_miim_park_write(unit, base_id + rtl8218b_0455A_mode2_perchip[i].phy, \
                            RTL8390_MAX_PAGE, 0x1f, \
                            (int)rtl8218b_0455A_mode2_perchip[i].reg,  \
                            rtl8218b_0455A_mode2_perchip[i].val);
                }

                for(port_id = 0; port_id < 8; port_id++)
                {
                    for (i=0; i<(sizeof(rtl8218b_0455A_mode2_perport)/sizeof(phy_patch_array_type1_t)); i++)
                    {
                        if((i == 2))
                            osal_time_usleep(500*1000);  /*Wait for 8018B leave the command state*/

                        hal_miim_park_write(unit, base_id + port_id, \
                                RTL8390_MAX_PAGE, 0x1f, \
                                (int)rtl8218b_0455A_mode2_perport[i].reg,  \
                                rtl8218b_0455A_mode2_perport[i].val);
                    }
                }
            }
            else if((val == 3) || (val == 5)) /* lan mode*/
            {
                for (i=0; i<(sizeof(rtl8218b_0455A_mode3_perchip)/sizeof(phy_patch_array_type0_t)); i++)
                {
                    hal_miim_park_write(unit, base_id + rtl8218b_0455A_mode3_perchip[i].phy, \
                            RTL8390_MAX_PAGE, 0x1f, \
                            (int)rtl8218b_0455A_mode3_perchip[i].reg,  \
                            rtl8218b_0455A_mode3_perchip[i].val);
                }

                for(port_id = 0; port_id < 8; port_id++)
                {
                    for (i=0; i<(sizeof(rtl8218b_0455A_mode3_perport)/sizeof(phy_patch_array_type1_t)); i++)
                    {
                        if((i == 2))
                            osal_time_usleep(500*1000);  /*Wait for 8018B leave the command state*/

                        hal_miim_park_write(unit, base_id + port_id, \
                                RTL8390_MAX_PAGE, 0x1f, \
                                (int)rtl8218b_0455A_mode3_perport[i].reg,  \
                                rtl8218b_0455A_mode3_perport[i].val);
                    }
                }

                /*Check the 8218B verA Patch Result*/
                hal_miim_write(unit, base_id, 0x0a42, 27, 0x8012); /*Reg 27 is PHY internal SRAM address*/
                hal_miim_read(unit, base_id, 0x0a42, 28, &val); /*Reg 28 is PHY internal SRAM address value*/
                if(val != 0x3f0f)
                {
                    RT_DBG(LOG_DEBUG, (MOD_HAL|MOD_SWITCH), "RTL8218B TCA Patch Failed 1!!!\n");
                }
                hal_miim_write(unit, base_id, 0x0a42, 27, 0x80d1);
                hal_miim_read(unit, base_id, 0x0a42, 28, &val);
                if(val != 0xa5aa)
                {
                    RT_DBG(LOG_DEBUG, (MOD_HAL|MOD_SWITCH), "RTL8218B TCA Patch Failed 2!!!\n");
                }
            } else {
                RT_DBG(LOG_DEBUG, (MOD_HAL|MOD_SWITCH), "### RTL8218B TCA in ERROR status %d\n", val);
                return ret;
            }
        }
        else if(cut_id == RTL8218B_TCA_CUT_B)
        {
            /* Per-Chip */
            for (i=0; i<(sizeof(rtl8218b_0455B_rtl8390_perchip)/sizeof(phy_patch_array_type0_t)); i++)
            {
                hal_miim_park_write(unit, base_id + rtl8218b_0455B_rtl8390_perchip[i].phy, \
                            RTL8390_MAX_PAGE, 0x1f, \
                            (int)rtl8218b_0455B_rtl8390_perchip[i].reg,  \
                            rtl8218b_0455B_rtl8390_perchip[i].val);
            }

            /* Per-Port */
            for(port_id = 0; port_id < 8; port_id++)
            {
                for (i=0; i<(sizeof(rtl8218b_0455B_rtl8390_perport)/sizeof(phy_patch_array_type1_t)); i++)
                {
                    hal_miim_park_write(unit, base_id + port_id, \
                                RTL8390_MAX_PAGE, 0x1f, \
                                (int)rtl8218b_0455B_rtl8390_perport[i].reg,  \
                                rtl8218b_0455B_rtl8390_perport[i].val);
                }
            }
        }
    }   /* ES */

    /* Set default value for reset checking in waMon */
    ret = hal_miim_write(unit, base_id, 0, 27, 0x801e);
    ret = hal_miim_write(unit, base_id, 0, 28, 0x1);

    /*rtl8390_phyPowerOn();*/
    for (i = base_id; i < (base_id + 8); ++i)
    {
        hal_miim_read(unit, i, 0, 0, &val);
        hal_miim_write(unit, i, 0, 0, val & ~(0x1 << 11));
    }

    /*Re-Patch PHYs which have been reseted*/
    /*Save polling mask*/
    for (i = base_id; i < (base_id + 8); ++i)
        hal_miim_pollingEnable_set(unit, i, restore_flag[(i - base_id)]);

    return RT_ERR_OK;
}   /* end of rtl8218b_rtl8390_config */


