/* Function Name:
 *      sub_phy_8214fc_mp_patch_set
 * Description:
 *      Patch the PHY:8214FC MP.
 * Input:
 *      unit   - unit id
 *      port   - PHY base port id
 * Output:
 *      None
 * Return:
 *      RT_ERR_OK
 *      RT_ERR_FAILED
 *      RT_ERR_NOT_INIT - The module is not initial
 *      RT_ERR_UNIT_ID  - invalid unit id
 *      RT_ERR_PORT_ID  - invalid port id
 *      RT_ERR_INPUT    - invalid input parameter
 * Note:
 *      None
 */
int32
sub_phy_8214fc_mp_patch_set(uint32 unit, rtk_port_t port)
{
    hal_control_t   *pHalCtrl;
    int32   ret = RT_ERR_FAILED;
    int32   i;

    RT_PARAM_CHK(((port % PORT_NUM_IN_8214FC) != 0), RT_ERR_PORT_ID);

    if ((pHalCtrl = hal_ctrlInfo_get(unit)) == NULL)
        return RT_ERR_FAILED;

#if defined(CONFIG_SDK_RTL8380)
    if ((RTL8382M_CHIP_ID == pHalCtrl->chip_id) || (RTL8380M_CHIP_ID == pHalCtrl->chip_id))
    {
        if((port % 8) == 0)
        {
            uint32 phy_data;
            uint32 port_id;

             /* Set 8214FC MP CHIP FLAG*/
             if ((ret = hal_miim_write(unit, port, 0, 30, 8)) != RT_ERR_OK)
                 return ret;

            if ((ret = hal_miim_read(unit, port, 0x268, 16, &phy_data)) != RT_ERR_OK)
                 return ret;

            phy_data &= ~(0xF<<12);
            phy_data |= (0xA<<12);

            if ((ret = hal_miim_write(unit, port, 0x268, 16, phy_data)) != RT_ERR_OK)
                 return ret;

             if ((ret = hal_miim_write(unit, port, 0, 30, 0)) != RT_ERR_OK)
                 return ret;


            /* Enable serdes always linkup settings */
            ret = hal_miim_write(unit,  port,  0,  30, 8);
            if(ret != RT_ERR_OK)
                return ret;

            ret = hal_miim_write(unit,  port,  0x404,  0x10, 0x9703);
            if(ret != RT_ERR_OK)
                return ret;

            ret = hal_miim_write(unit,  port,  0x424,  0x10, 0x9403);
            if(ret != RT_ERR_OK)
                return ret;

            ret = hal_miim_write(unit,  port,  0,  30, 0);
            if(ret != RT_ERR_OK)
                return ret;

            /* Set PKTGEN RXPATH is from MAC TX & Enable PKTGEN RX for Phy error counter */
            for(port_id = 0; port_id < 4; port_id++)
            {
                 /* Set Force Copper*/
                if ((ret = hal_miim_write(unit, port+port_id, 0, 30, 0x1)) != RT_ERR_OK)
                     return ret;

                ret = hal_miim_read(unit,  port+port_id,  0xc80,  16, &phy_data);
                if(ret != RT_ERR_OK)
                    return ret;
                phy_data &= ~0xF;
                phy_data |= 0x1<<2;
                phy_data |= 0x2<<0;
                ret = hal_miim_write(unit,  port+port_id,  0xc80,  16, phy_data);
                if(ret != RT_ERR_OK)
                    return ret;

                 /* Set Enable Auto mode*/
                 if ((ret = hal_miim_write(unit, port+port_id, 0, 30, 0x0)) != RT_ERR_OK)
                     return ret;
            }

            /* Re-Patch 8214FC*/
            if ((ret = rtl8380_rtl8214fc_mp_config(unit, port)) != RT_ERR_OK)
                return ret;
        }
    }
#endif


#if defined(CONFIG_SDK_RTL8390) || defined(CONFIG_SDK_RTL8350)
    if (HAL_IS_RTL8390_FAMILY_ID(unit) || HAL_IS_RTL8350_FAMILY_ID(unit))
    {
        RT_DBG(LOG_DEBUG, (MOD_HAL|MOD_SWITCH), "Do the 8214FC MP Re-Patch Operation!\n", port);
        if ((ret = rtl8390_rtl8214fc_config(unit, port)) != RT_ERR_OK)
            return ret;
    }
#endif

    for (i = 0; i < PORT_NUM_IN_8214FC; ++i)
        hal_ctrl[unit].pPhy_ctrl[port]->pPhydrv->fPhydrv_init(unit, port + i);

    ret = RT_ERR_OK;
    return ret;

} /* end of sub_phy_8214fc_mp_patch_set */

