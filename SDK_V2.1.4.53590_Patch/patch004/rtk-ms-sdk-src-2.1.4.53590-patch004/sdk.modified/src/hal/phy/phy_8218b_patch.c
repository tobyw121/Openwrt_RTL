/* Function Name:
 *      rtl8380_rtl8214fc_mp_config
 * Description:
 *      Patch the PHY:8214fc for RTL8380.
 * Input:
 *      unit   - unit id
 *      port   - port id
 * Output:
 *      None
 * Return:
 *      RT_ERR_OK
 *      RT_ERR_FAILED
 *      RT_ERR_NOT_INIT - The module is not initial
 *      RT_ERR_UNIT_ID  - invalid unit id
 *      RT_ERR_PORT_ID  - invalid port id
 *      RT_ERR_INPUT    - invalid input parameter
 * Note:
 *      None
 */
int32
rtl8380_rtl8214fc_mp_config(uint32 unit, rtk_port_t port)
{
    uint32 i;
    uint32 val;
    int32  ret = RT_ERR_FAILED;
    uint32 cut_id;
    uint32 port_id;
    uint32 loop;

    /*Port should be base-port*/
    if((port%8) != 0)
    {
        ret = RT_ERR_OK;
        return ret;
    }

    /*Switch to Copper address*/
    if ((ret = hal_miim_write(unit, port, 0, 30, 0x0001)) != RT_ERR_OK)
    return ret;

    if ((ret = hal_miim_write(unit, port, 0, 31, 0x0a42)) != RT_ERR_OK)
    return ret;

    /*Check the 8218B internal chip ID*/
    if ((ret = hal_miim_write(unit, port, 31, 27, 0x0002)) != RT_ERR_OK)
    return ret;

    if ((ret = hal_miim_read(unit, port, 31, 28, &val)) != RT_ERR_OK)
    return ret;

     /*Check the 8214FC internal cut ID*/
    if ((ret = hal_miim_write(unit, port, 4095, 27, 0x0004)) != RT_ERR_OK)
    return ret;

    if ((ret = hal_miim_read(unit, port, 4095, 28, &cut_id)) != RT_ERR_OK)
    return ret;

    /*Back to Auto address*/
    if ((ret = hal_miim_write(unit, port, 0, 30, 0x0000)) != RT_ERR_OK)
    return ret;

    if(val == 0x6276)
    {
       if(0x0 == cut_id)
       {
            /* Per-Chip */
            for (i=0; i<(sizeof(rtl8380_8214fc_acut_perchip)/sizeof(phy_patch_array_type0_t)); i++)
            {
                 ret = hal_miim_write(unit, port + rtl8380_8214fc_acut_perchip[i].phy, \
                    4095, rtl8380_8214fc_acut_perchip[i].reg, rtl8380_8214fc_acut_perchip[i].val);
                 if(ret  != RT_ERR_OK)
                    return ret;
            }
       }
       else
       {
            /* Per-Chip */
            for (i=0; i<(sizeof(rtl8380_8214fc_bcut_perchip)/sizeof(phy_patch_array_type0_t)); i++)
            {
                 ret = hal_miim_write(unit, port + rtl8380_8214fc_bcut_perchip[i].phy, \
                    4095, rtl8380_8214fc_bcut_perchip[i].reg, rtl8380_8214fc_bcut_perchip[i].val);
                 if(ret  != RT_ERR_OK)
                    return ret;
            }

           /* Set Copper mode*/
            for(port_id = 0; port_id < 4; port_id++)
            {
                hal_miim_write(unit, port+port_id, 0, 30, 0x1);
            }

            /*Enable Phy*/
            for(port_id = 0; port_id < 4; port_id++)
            {
               hal_miim_write(unit, port+port_id, 0xfff, 0x1f, 0x0000);
               hal_miim_write(unit, port+port_id, 0xfff, 0x00, 0x1140);
            }
            osal_time_usleep(1000); /* delay 1mS */

            /*Disable AutoSending Featrue*/
            for(port_id = 0; port_id < 4; port_id++)
            {
                for(loop = 0; loop < 100; loop++)
                {
                    hal_miim_read(unit, port + port_id, 0x0a42, 0x10, &val);
                    if((val & 0x7)>=3)break;
                }
            }

            /*Patch request*/
            for(port_id = 0; port_id < 4; port_id++)
            {
                hal_miim_write(unit, port+port_id, 0xfff, 0x1f, 0x0b82);
                hal_miim_write(unit, port+port_id, 0xfff, 0x10, 0x0010);
            }
            osal_time_usleep(300 * 1000); /* delay 300mS */

            /*Patch ready check*/
            for(port_id = 0; port_id < 4; port_id++)
            {
                for(loop = 0; loop < 100; loop++)
                {
                    hal_miim_read(unit, port + port_id, 0xb80, 0x10, &val);
                    if(val & 0x40)break;
                }
            }

            /*Use broadcast ID method to pathc internal phy*/
            hal_miim_write(unit, port, 0xfff, 0x1f, 0x0000);
            hal_miim_write(unit, port, 0xfff, 0x001d, 0x0008);
            hal_miim_write(unit, port, 0xfff, 0x001f, 0x266);
            hal_miim_write(unit, port, 0xfff, 0x16, 0xff00+port);
            hal_miim_write(unit, port, 0xfff, 0x1f, 0x0000);
            hal_miim_write(unit, port, 0xfff, 0x1d, 0x0000);
            osal_time_usleep(1000); /* delay 1mS */

            /* Per-Port */
            for (i=0; i<(sizeof(rtl8380_8214fc_bcut_perport)/sizeof(phy_patch_array_type1_t)); i++)
            {
                hal_miim_write(unit, port, \
                    4095, (int)rtl8380_8214fc_bcut_perport[i].reg, rtl8380_8214fc_bcut_perport[i].val);
            }

            /*Disable broadcast ID*/
            hal_miim_write(unit, port, 0xfff, 0x1f, 0x0000);
            hal_miim_write(unit, port, 0xfff, 0x001d, 0x0008);
            hal_miim_write(unit, port, 0xfff, 0x001f, 0x266);
            hal_miim_write(unit, port, 0xfff, 0x16, 0+port);
            hal_miim_write(unit, port, 0xfff, 0x1f, 0x0000);
            hal_miim_write(unit, port, 0xfff, 0x1d, 0x0000);
            osal_time_usleep(1000); /* delay 1mS */

            /* Set Enable Auto mode*/
            for(port_id = 0; port_id < 4; port_id++)
            {
                hal_miim_write(unit, port+port_id, 0, 30, 0);
            }

       }

        ret = RT_ERR_OK;
    }

    return ret;
}



