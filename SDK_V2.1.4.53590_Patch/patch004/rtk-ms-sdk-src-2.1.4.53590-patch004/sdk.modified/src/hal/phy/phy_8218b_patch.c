/* Function Name:
 *      rtl8380_rtl8218b_config
 * Description:
 *      Patch the PHY:8218B for RTL8380.
 * Input:
 *      unit   - unit id
 *      port   - port id
 * Output:
 *      None
 * Return:
 *      RT_ERR_OK
 *      RT_ERR_FAILED
 *      RT_ERR_NOT_INIT - The module is not initial
 *      RT_ERR_UNIT_ID  - invalid unit id
 *      RT_ERR_PORT_ID  - invalid port id
 *      RT_ERR_INPUT    - invalid input parameter
 * Note:
 *      None
 */
int32
rtl8380_rtl8218b_config(uint32 unit, rtk_port_t port)
{
    uint32 i;
    uint32 loop;
    rtk_port_t port_id;
    uint32 val,cut_id;
    unsigned int rtl8218b_ipd_flg = 0;
    int32  ret = RT_ERR_FAILED;

    /*Port should be base-port*/
    if((port%8) != 0)
    {
        ret = RT_ERR_OK;
        return ret;
    }

    /*Check the 8218B internal chip ID*/
    if ((ret = hal_miim_write(unit, port, 31, 27, 0x0002)) != RT_ERR_OK)
    return ret;

    if ((ret = hal_miim_read(unit, port, 31, 28, &val)) != RT_ERR_OK)
    return ret;

    if(val == 0x6276)
    {

        /*CHIP Cut Version*/
        if ((ret = hal_miim_write(unit, port, 4095, 0x1f, 0x0)) != RT_ERR_OK)
           return ret;

        if ((ret = hal_miim_write(unit, port, 4095, 0x1b, 0x4)) != RT_ERR_OK)
           return ret;

        if ((ret = hal_miim_read(unit, port, 4095, 0x1c, &cut_id)) != RT_ERR_OK)
           return ret;


         /* Per-Chip */
        if(0 == cut_id)
        {
            for (i=0; i<(sizeof(rtl8380_8218b_acut_perchip)/sizeof(phy_patch_array_type0_t)); i++)
            {
                 ret = hal_miim_write(unit, port + rtl8380_8218b_acut_perchip[i].phy, \
                    4095, rtl8380_8218b_acut_perchip[i].reg, rtl8380_8218b_acut_perchip[i].val);
                 if(ret  != RT_ERR_OK)
                    return ret;
            }
        }
        else
        {
            for (i=0; i<(sizeof(rtl8380_8218b_bcut_perchip)/sizeof(phy_patch_array_type0_t)); i++)
            {
                 ret = hal_miim_write(unit, port + rtl8380_8218b_bcut_perchip[i].phy, \
                    4095, rtl8380_8218b_bcut_perchip[i].reg, rtl8380_8218b_bcut_perchip[i].val);
                 if(ret  != RT_ERR_OK)
                    return ret;
            }
        }


        /*Enable Phy*/
        for(port_id = 0; port_id < 8; port_id++)
        {
            if ((ret = hal_miim_write(unit, port+port_id, 0xfff, 0x1f, 0x0000)) != RT_ERR_OK)
                return ret;
            if ((ret = hal_miim_write(unit, port+port_id, 0xfff, 0x00, 0x1140)) != RT_ERR_OK)
                return ret;
        }

        osal_time_usleep(100 * 1000); /* delay 100mS */

        /*Patch request*/
        for(port_id = 0; port_id < 8; port_id++)
        {
            if ((ret = hal_miim_write(unit,  port+port_id, 0xfff, 0x1f, 0x0b82)) != RT_ERR_OK)
                return ret;
            if ((ret = hal_miim_write(unit,  port+port_id, 0xfff, 0x10, 0x0010)) != RT_ERR_OK)
                return ret;
        }

        osal_time_usleep(300 * 1000); /* delay 300mS */

        /*Patch ready check*/
        for(port_id = 0; port_id < 8; port_id++)
        {
            for(loop = 0; loop < 100; loop++)
            {
                if ((ret = hal_miim_read(unit,  port + port_id, 0xb80, 0x10, &val)) != RT_ERR_OK)
                        return ret;
                if(val & 0x40)break;
            }

            if(loop >= 100)
            {
                osal_printf("18b phy port %d not ready!\n",port_id+ port);
                return RT_ERR_FAILED;
            }
        }

        /*Use broadcast ID method to pathc internal phy*/
        if ((ret = hal_miim_write(unit, port, 0xfff, 0x1f, 0x0000)) != RT_ERR_OK)
                return ret;
        if ((ret = hal_miim_write(unit, port, 0xfff, 0x001d, 0x0008)) != RT_ERR_OK)
                return ret;
        if ((ret = hal_miim_write(unit, port, 0xfff, 0x001f, 0x266)) != RT_ERR_OK)
                return ret;
        if ((ret = hal_miim_write(unit, port, 0xfff, 0x16, 0xff00+ port)) != RT_ERR_OK)
                return ret;
        if ((ret = hal_miim_write(unit, port, 0xfff, 0x1f, 0x0000)) != RT_ERR_OK)
                return ret;
        if ((ret = hal_miim_write(unit, port, 0xfff, 0x1d, 0x0000)) != RT_ERR_OK)
                return ret;

        osal_time_usleep(1000); /* delay 1mS */


        /* Per-Port */
        if(0 == cut_id)
        {
            /* Per-Port */
            for (i=0; i<(sizeof(rtl8380_8218b_acut_perport)/sizeof(phy_patch_array_type1_t)); i++)
            {
                ret = hal_miim_write(unit, port, 4095, rtl8380_8218b_acut_perport[i].reg, \
                        rtl8380_8218b_acut_perport[i].val);
            }

            /*Disable broadcast ID*/
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x1f, 0x0000)) != RT_ERR_OK)
                    return ret;
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x001d, 0x0008)) != RT_ERR_OK)
                    return ret;
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x001f, 0x266)) != RT_ERR_OK)
                    return ret;
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x16, 0+ port)) != RT_ERR_OK)
                    return ret;
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x1f, 0x0000)) != RT_ERR_OK)
                    return ret;
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x1d, 0x0000)) != RT_ERR_OK)
                    return ret;
        }
        else
        {
            /* Per-Port */
            /* IPD FLAG */
            hal_miim_write(unit, port, 0xfff, 30, 8);
            hal_miim_write(unit,port, 0x26e, 17, 0xb);
            hal_miim_write(unit,port, 0x26e, 16, 0x2);
            osal_time_usleep(1000);
            hal_miim_read(unit,port, 0x26e, 19, &rtl8218b_ipd_flg);
            hal_miim_write(unit,port, 0, 30, 0);
            rtl8218b_ipd_flg = (((rtl8218b_ipd_flg >> 4) & 0xf)==0x1) ? 0x1 : 0x0;

            if(rtl8218b_ipd_flg)
            {
                for (i=0; i<(sizeof(rtl8380_8218b_bcut_ipd_perport)/sizeof(phy_patch_array_type1_t)); i++)
                {
                    ret = hal_miim_write(unit, port, 4095, rtl8380_8218b_bcut_ipd_perport[i].reg, \
                            rtl8380_8218b_bcut_ipd_perport[i].val);
                }
            }
            else
            {
                /* Per-Port */
                for (i=0; i<(sizeof(rtl8380_8218b_bcut_perport)/sizeof(phy_patch_array_type1_t)); i++)
                {
                    ret = hal_miim_write(unit, port, 4095, rtl8380_8218b_bcut_perport[i].reg, \
                            rtl8380_8218b_bcut_perport[i].val);
                }
            }


            /*Disable broadcast ID*/
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x1f, 0x0000)) != RT_ERR_OK)
                    return ret;
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x001d, 0x0008)) != RT_ERR_OK)
                    return ret;
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x001f, 0x266)) != RT_ERR_OK)
                    return ret;
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x16, 0+ port)) != RT_ERR_OK)
                    return ret;
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x1f, 0x0000)) != RT_ERR_OK)
                    return ret;
            if ((ret = hal_miim_write(unit, port, 0xfff, 0x1d, 0x0000)) != RT_ERR_OK)
                    return ret;

            /* IPD_ENHANCE */
            if(rtl8218b_ipd_flg)
            {
                hal_miim_write(unit, port+0, 0xfff, 0x1f, 0x0a42);
                hal_miim_write(unit, port+0, 0xfff, 0x16, 0x0f91);

                hal_miim_write(unit, port+1, 0xfff, 0x1f, 0x0a42);
                hal_miim_write(unit, port+1, 0xfff, 0x16, 0x0fd1);

                hal_miim_write(unit, port+2, 0xfff, 0x1f, 0x0a42);
                hal_miim_write(unit, port+2, 0xfff, 0x16, 0x0fd1);

                hal_miim_write(unit, port+3, 0xfff, 0x1f, 0x0a42);
                hal_miim_write(unit, port+3, 0xfff, 0x16, 0x0f51);

                hal_miim_write(unit, port+4, 0xfff, 0x1f, 0x0a42);
                hal_miim_write(unit, port+4, 0xfff, 0x16, 0x0f91);

                hal_miim_write(unit, port+5, 0xfff, 0x1f, 0x0a42);
                hal_miim_write(unit, port+5, 0xfff, 0x16, 0x0fd1);

                hal_miim_write(unit, port+6, 0xfff, 0x1f, 0x0a42);
                hal_miim_write(unit, port+6, 0xfff, 0x16, 0x0fd1);

                hal_miim_write(unit, port+7, 0xfff, 0x1f, 0x0a42);
                hal_miim_write(unit, port+7, 0xfff, 0x16, 0x0f51);
            }
        }

        osal_time_usleep(1000); /* delay 1mS */

        ret = RT_ERR_OK;
    }

    return ret;
}


