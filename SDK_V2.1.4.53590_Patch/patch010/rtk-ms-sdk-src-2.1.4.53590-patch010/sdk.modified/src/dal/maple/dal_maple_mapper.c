/* Function Name:
 *      dal_maple_init
 * Description:
 *      Initilize DAL of smart switch
 * Input:
 *      unit - unit id
 * Output:
 *      None
 * Return:
 *      RT_ERR_OK     - initialize success
 *      RT_ERR_FAILED - initialize fail
 * Note:
 *      RTK must call this function before do other kind of action.
 */
int dal_maple_init(uint32 unit)
{
    int32 ret = RT_ERR_FAILED;

    /* Same initialize sequence as original rtk_init function */
    if ((ret = dal_maple_switch_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_switch_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_port_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_port_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_led_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_led_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_eee_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_eee_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_sec_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_sec_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_trunk_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_trunk_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_qos_init(unit, RTK_DEFAULT_QOS_QUEUE_NUMBER)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_qos_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_rate_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_rate_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_flowctrl_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_flowctrl_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_vlan_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_vlan_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_stp_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_stp_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_l2_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_l2_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_l3_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_l3_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_time_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_time_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_trap_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_trap_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_mirror_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_mirror_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_stat_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_stat_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_acl_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_acl_init Failed!");
        return ret;
    }

    if ((ret = dal_maple_diag_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_maple_diag_init Failed!");
        return ret;
    }

    return RT_ERR_OK;
} /* end of dal_maple_init */
