/*
 * Private compatibility vocabulary for the legacy rtl_net80211_* adapter.
 *
 * Linux 6.6 builds do not expose the historical BSD/net80211 ioctl ABI to
 * userspace.  cfg80211 translates into these values only inside the driver,
 * which lets the proven vendor security/MLME helpers remain unchanged while
 * the public control plane is nl80211/cfg80211.
 */
