/* Function Name:
 *      phy_8218_eeeEnable_set
 * Description:
 *      Set enable status of EEE function in the specified port.
 * Input:
 *      unit   - unit id
 *      port   - port id
 *      enable - enable status of EEE
 * Output:
 *      None
 * Return:
 *      RT_ERR_OK
 *      RT_ERR_FAILED
 *      RT_ERR_NOT_INIT - The module is not initial
 *      RT_ERR_UNIT_ID  - invalid unit id
 *      RT_ERR_PORT_ID  - invalid port id
 *      RT_ERR_INPUT    - invalid input parameter
 * Note:
 *      None
 */
int32
phy_8218_eeeEnable_set(uint32 unit, rtk_port_t port, rtk_enable_t enable)
{
    uint32  phyData0;
    int32   ret = RT_ERR_FAILED;
    rtk_enable_t     an_enable;

    phy_common_autoNegoEnable_get(unit, port, &an_enable);

    if (ENABLED == enable)
    {
        //## ext page 32
        if ((ret = hal_miim_write(unit, port, 7, 0x1e, 0x0020)) != RT_ERR_OK)
            return ret;
        if ((ret = hal_miim_write(unit, port, 7, 0x17, 0x000a)) != RT_ERR_OK)
            return ret;
        if ((ret = hal_miim_write(unit, port, 7, 0x1b, 0x2fca)) != RT_ERR_OK)
            return ret;
        if ((ret = hal_miim_write(unit, port, 7, 0x15, 0x0100)) != RT_ERR_OK)
            return ret;

        //###### negear EEE Nway ability autooff
        if ((ret = hal_miim_write(unit, port, 5, 0x1f, 0x0005)) != RT_ERR_OK)
            return ret;
        if ((ret = hal_miim_write(unit, port, 5, 0x05, 0x8b84)) != RT_ERR_OK)
            return ret;
        //if ((ret = hal_miim_write(unit, port, 5, 0x06, 0x0026)) != RT_ERR_OK)
        //    return ret;
        if ((ret = hal_miim_write(unit, port, 5, 0x06, 0x0062)) != RT_ERR_OK)
            return ret;
        if ((ret = hal_miim_write(unit, port, 0, 0x1f, 0x0000)) != RT_ERR_OK)
            return ret;
    }
    else
    {
        //###### negear EEE Nway ability autooff
        if ((ret = hal_miim_write(unit, port, 5, 0x1f, 0x0005)) != RT_ERR_OK)
            return ret;
        if ((ret = hal_miim_write(unit, port, 5, 0x05, 0x8b84)) != RT_ERR_OK)
            return ret;
        if ((ret = hal_miim_write(unit, port, 5, 0x06, 0x0042)) != RT_ERR_OK)
            return ret;
        if ((ret = hal_miim_write(unit, port, 0, 0x1f, 0x0000)) != RT_ERR_OK)
            return ret;

        //## ext page 32
        if ((ret = hal_miim_write(unit, port, 7, 0x1e, 0x0020)) != RT_ERR_OK)
            return ret;
        if ((ret = hal_miim_write(unit, port, 7, 0x17, 0x000a)) != RT_ERR_OK)
            return ret;
        if ((ret = hal_miim_write(unit, port, 7, 0x1b, 0x2f4a)) != RT_ERR_OK)
            return ret;
        if ((ret = hal_miim_write(unit, port, 7, 0x15, 0x0000)) != RT_ERR_OK)
            return ret;
    }

    /* Force re-autonegotiation if AN is on*/
    if (ENABLED == an_enable)
    {
        if ((ret = hal_miim_read(unit, port, PHY_PAGE_0, PHY_CONTROL_REG, &phyData0)) != RT_ERR_OK)
            return ret;

        phyData0 = phyData0 & ~(RestartAutoNegotiation_MASK);
        phyData0 = phyData0 | (an_enable << RestartAutoNegotiation_OFFSET);

        if ((ret = hal_miim_write(unit, port, PHY_PAGE_0, PHY_CONTROL_REG, phyData0)) != RT_ERR_OK)
            return ret;
    }

    return ret;
} /* end of phy_8218_eeeEnable_set */

/* Function Name:
 *      phy_8218_crossOverMode_get
 * Description:
 *      Get cross over mode in the specified port.
 * Input:
 *      unit  - unit id
 *      port  - port id
 * Output:
 *      pMode - pointer to cross over mode
 * Return:
 *      RT_ERR_OK
 *      RT_ERR_FAILED
 *      RT_ERR_UNIT_ID      - invalid unit id
 *      RT_ERR_PORT_ID      - invalid port id
 *      RT_ERR_NULL_POINTER - input parameter may be null pointer
 * Note:
 *      Following value is valid
 *      - PORT_CROSSOVER_MODE_AUTO
 *      - PORT_CROSSOVER_MODE_MDI
 *      - PORT_CROSSOVER_MODE_MDIX
 */
int32
phy_8218_crossOverMode_get(uint32 unit, rtk_port_t port, rtk_port_crossOver_mode_t *pMode)
{
    int32   ret;
    uint32  phyData, force_mode, mdi;

    /* get value from CHIP*/
    if ((ret = hal_miim_write(unit, port, 7, 0x1e, 0x002d)) != RT_ERR_OK)
        return ret;

    if ((ret = hal_miim_read(unit, port, 7, 0x18, &phyData)) != RT_ERR_OK)
        return ret;
    force_mode = (phyData >> 5) & 0x1;

    if ((ret = hal_miim_read(unit, port, 0, 0x10, &phyData)) != RT_ERR_OK)
        return ret;
    mdi = (phyData >> 5) & 0x1;

    if (force_mode)
    {
        if (mdi)
            *pMode = PORT_CROSSOVER_MODE_MDI;
        else
            *pMode = PORT_CROSSOVER_MODE_MDIX;
    }
    else
        *pMode = PORT_CROSSOVER_MODE_AUTO;

    return ret;
} /* end of phy_8218_crossOverMode_get */

/* Function Name:
 *      phy_8218_crossOverMode_set
 * Description:
 *      Set cross over mode in the specified port.
 * Input:
 *      unit - unit id
 *      port - port id
 *      mode - cross over mode
 * Output:
 *      None
 * Return:
 *      RT_ERR_OK
 *      RT_ERR_FAILED
 *      RT_ERR_UNIT_ID - invalid unit id
 *      RT_ERR_PORT_ID - invalid port id
 *      RT_ERR_INPUT   - invalid input parameter
 * Note:
 *      Following value is valid
 *      - PORT_CROSSOVER_MODE_AUTO
 *      - PORT_CROSSOVER_MODE_MDI
 *      - PORT_CROSSOVER_MODE_MDIX
 */
int32
phy_8218_crossOverMode_set(uint32 unit, rtk_port_t port, rtk_port_crossOver_mode_t mode)
{
    int32   ret;
    uint32  phyData, force_mode, mdi;

    switch (mode)
    {
        case PORT_CROSSOVER_MODE_AUTO:
            force_mode = 0;
            mdi = 1;
            break;
        case PORT_CROSSOVER_MODE_MDI:
            force_mode = 1;
            mdi = 1;
            break;
        case PORT_CROSSOVER_MODE_MDIX:
            force_mode = 1;
            mdi = 0;
            break;
        default:
            return RT_ERR_INPUT;
    }

    /* get value from CHIP*/
    if ((ret = hal_miim_write(unit, port, 7, 0x1e, 0x002d)) != RT_ERR_OK)
        return ret;
    if ((ret = hal_miim_read(unit, port, 7, 0x18, &phyData)) != RT_ERR_OK)
        return ret;
    phyData &= ~(1 << 5);
    phyData |= (force_mode << 5);
    if ((ret = hal_miim_write(unit, port, 7, 0x18, phyData)) != RT_ERR_OK)
        return ret;

    if ((ret = hal_miim_read(unit, port, 0, 0x10, &phyData)) != RT_ERR_OK)
        return ret;
    phyData &= ~(1 << 5);
    phyData |= (mdi << 5);
    if ((ret = hal_miim_write(unit, port, 0, 0x10, phyData)) != RT_ERR_OK)
        return ret;

    return ret;
} /* end of phy_8218_crossOverMode_set */

/* Function Name:
 *      phy_8218_linkDownPowerSavingEnable_get
 * Description:
 *      Get the status of link-down power saving of the specific port in the specific unit
 * Input:
 *      unit    - unit id
 *      port    - port id
 * Output:
 *      pEnable - pointer to status of link-down power saving
 * Return:
 *      RT_ERR_OK
 *      RT_ERR_FAILED
 * Note:
 *      1. The RTL8218 is supported the per-port link-down power saving
 */
int32
phy_8218_linkDownPowerSavingEnable_get(uint32 unit, rtk_port_t port, rtk_enable_t *pEnable)
{
    uint32  value;
    int32   ret = RT_ERR_FAILED;

    if ((ret = hal_miim_read(unit, port, 0, 21, &value)) != RT_ERR_OK)
        return ret;
    if (((value >> 12) & 0x1) == 0x1)
        *pEnable = ENABLED;
    else
        *pEnable = DISABLED;

    return RT_ERR_OK;
} /* end of phy_8218_linkDownPowerSavingEnable_get */

/* Function Name:
 *      phy_8218_linkDownPowerSavingEnable_set
 * Description:
 *      Set the status of link-down power saving of the specific port in the specific unit
 * Input:
 *      unit   - unit id
 *      port   - port id
 *      enable - status of link-down power saving
 * Output:
 *      None
 * Return:
 *      RT_ERR_OK
 *      RT_ERR_FAILED
 * Note:
 *      1. The RTL8218 is supported the per-port link-down power saving
 */
int32
phy_8218_linkDownPowerSavingEnable_set(uint32 unit, rtk_port_t port, rtk_enable_t enable)
{
    uint32  value;
    int32   ret = RT_ERR_FAILED;

    /* For Link-Down Power Saving (per-port) */
    if ((ret = hal_miim_read(unit, port, 0, 21, &value)) != RT_ERR_OK)
        return ret;
    value &= ~(0x1 << 12);
    if (ENABLED == enable)
    {
        value |= (0x1 << 12);
    }
    if ((ret = hal_miim_write(unit, port, 0, 21, value)) != RT_ERR_OK)
        return ret;

    return RT_ERR_OK;
} /* end of phy_8218_linkDownPowerSavingEnable_set */

