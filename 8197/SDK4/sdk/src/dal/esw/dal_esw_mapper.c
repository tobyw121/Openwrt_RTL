/* Function Name: 
 *      dal_esw_init
 * Description: 
 *      Initilize DAL of enterprise switch 
 * Input:  
 *      unit - unit id
 * Output: 
 *      None 
 * Return: 
 *      RT_ERR_OK     - initialize success
 *      RT_ERR_FAILED - initialize fail
 * Note: 
 *      RTK must call this function before do other kind of action.
 */ 
int dal_esw_init(uint32 unit)
{
    int32 ret = RT_ERR_FAILED;
    
    /* Same initialize sequence as original rtk_init function */
    if ((ret = dal_esw_switch_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_switch_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_port_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_port_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_led_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_led_init Failed!");
        return ret;
    }

    if ((ret = dal_esw_eee_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_eee_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_trunk_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_trunk_init Failed!");
        return ret;
    }

    if ((ret = dal_esw_qos_init(unit, RTK_DEFAULT_QOS_QUEUE_NUMBER)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_qos_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_rate_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_rate_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_flowctrl_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_flowctrl_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_vlan_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_vlan_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_stp_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_stp_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_l2_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_l2_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_l3_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_l3_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_dot1x_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_dot1x_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_trap_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_trap_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_mirror_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_mirror_init Failed!");
        return ret;
    } 

    if ((ret = dal_esw_stat_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_stat_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_sec_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_sec_init Failed!");
        return ret;
    }

    if ((ret = dal_esw_oam_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_oam_init Failed!");
        return ret;
    }
    
    if ((ret = dal_esw_pie_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_pie_init Failed!");
        return ret;
    }

    if ((ret = dal_esw_diag_init(unit)) != RT_ERR_OK)
    {
        RT_DBG(LOG_MAJOR_ERR, MOD_DAL, "dal_esw_diag_init Failed!");
        return ret;
    }

    return RT_ERR_OK;
} /* end of dal_esw_init */
